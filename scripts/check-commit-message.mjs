#!/usr/bin/env node
// Guards the commit log against machine-authored trailers and boilerplate.
//
// Usage:
//   node scripts/check-commit-message.mjs .git/COMMIT_EDITMSG   (husky commit-msg)
//   node scripts/check-commit-message.mjs --range origin/main..HEAD   (CI)

import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'

const FORBIDDEN = [
  { label: 'a Co-Authored-By trailer', pattern: /^\s*co-authored-by\s*:/im },
  { label: 'a Signed-off-by trailer', pattern: /^\s*signed-off-by\s*:/im },
  { label: '"generated with" boilerplate', pattern: /generated\s+with/i },
  { label: '"generated by" boilerplate', pattern: /generated\s+by/i }
]

const NUL = String.fromCharCode(0)

/**
 * @param {string} message
 * @returns {string[]} one label per rule the message violates
 */
export function findViolations(message) {
  // git strips comment lines before writing the commit, so the editor template
  // must not fail the check while it is still in the file.
  const body = message
    .split('\n')
    .filter(line => !line.startsWith('#'))
    .join('\n')

  return FORBIDDEN.filter(rule => rule.pattern.test(body)).map(rule => rule.label)
}

function reportAndExit(entries) {
  const failures = entries.filter(entry => entry.violations.length > 0)
  if (failures.length === 0) {
    return
  }

  console.error('Commit message check failed.\n')
  for (const failure of failures) {
    console.error(`  ${failure.name}`)
    for (const violation of failure.violations) {
      console.error(`    - contains ${violation}`)
    }
    console.error('')
  }
  console.error('Hermie commit messages carry no attribution trailers and no tooling boilerplate.')
  console.error('See CONTRIBUTING.md for the commit rules.')
  process.exit(1)
}

function checkRange(range) {
  const raw = execFileSync('git', ['log', `--format=%H${NUL}%B${NUL}${NUL}`, range], { encoding: 'utf8' })

  const entries = raw
    .split(NUL + NUL)
    .map(part => part.trim())
    .filter(Boolean)
    .map(part => {
      const [sha = '', message = ''] = part.split(NUL)
      return { name: `commit ${sha.slice(0, 8)}`, violations: findViolations(message) }
    })

  reportAndExit(entries)
}

function checkFile(path) {
  reportAndExit([{ name: path, violations: findViolations(readFileSync(path, 'utf8')) }])
}

function main(argv) {
  const rangeIndex = argv.indexOf('--range')
  if (rangeIndex !== -1) {
    const range = argv[rangeIndex + 1]
    if (!range) {
      console.error('--range needs a commit range, for example origin/main..HEAD')
      process.exit(2)
    }
    checkRange(range)
    return
  }

  const path = argv.find(arg => !arg.startsWith('-'))
  if (!path) {
    console.error('Pass a commit message file, or --range <range>.')
    process.exit(2)
  }
  checkFile(path)
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  main(process.argv.slice(2))
}
